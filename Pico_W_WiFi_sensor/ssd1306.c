// Send command to SSD1306
static void ssd1306_send_command(uint8_t cmd) {
    uint8_t buf[2] = {0x00, cmd};
    i2c_write_blocking(ssd1306_i2c, SSD1306_I2C_ADDR, buf, 2, false);
}

// Send data to SSD1306
static void ssd1306_send_data(uint8_t *data, size_t len) {
    uint8_t buf[len + 1];
    buf[0] = 0x40;
    memcpy(buf + 1, data, len);
    i2c_write_blocking(ssd1306_i2c, SSD1306_I2C_ADDR, buf, len + 1, false);
}

bool ssd1306_init(void *i2c, uint8_t sda_pin, uint8_t scl_pin) {
    ssd1306_i2c = (i2c_inst_t *)i2c;
    
    // Initialize I2C
    i2c_init(ssd1306_i2c, 400 * 1000); // 400kHz
    gpio_set_function(sda_pin, GPIO_FUNC_I2C);
    gpio_set_function(scl_pin, GPIO_FUNC_I2C);
    gpio_pull_up(sda_pin);
    gpio_pull_up(scl_pin);
    
    sleep_ms(100);
    
    // Initialize SSD1306
    ssd1306_send_command(SSD1306_DISPLAY_OFF);
    ssd1306_send_command(SSD1306_SET_DISPLAY_CLOCK_DIV);
    ssd1306_send_command(0x80);
    ssd1306_send_command(SSD1306_SET_MULTIPLEX);
    ssd1306_send_command(0x3F);
    ssd1306_send_command(SSD1306_SET_DISPLAY_OFFSET);
    ssd1306_send_command(0x00);
    ssd1306_send_command(SSD1306_SET_START_LINE | 0x00);
    ssd1306_send_command(SSD1306_CHARGE_PUMP);
    ssd1306_send_command(0x14);
    ssd1306_send_command(SSD1306_MEMORY_MODE);
    ssd1306_send_command(0x00);
    ssd1306_send_command(SSD1306_SEG_REMAP | 0x01);
    ssd1306_send_command(SSD1306_COM_SCAN_DEC);
    ssd1306_send_command(SSD1306_SET_COM_PINS);
    ssd1306_send_command(0x12);
    ssd1306_send_command(SSD1306_SET_CONTRAST);
    ssd1306_send_command(0xCF);
    ssd1306_send_command(SSD1306_SET_PRECHARGE);
    ssd1306_send_command(0xF1);
    ssd1306_send_command(SSD1306_SET_VCOM_DETECT);
    ssd1306_send_command(0x40);
    ssd1306_send_command(SSD1306_DISPLAY_ALL_ON_RESUME);
    ssd1306_send_command(SSD1306_NORMAL_DISPLAY);
    ssd1306_send_command(SSD1306_DISPLAY_ON);
    
    ssd1306_clear();
    ssd1306_show();
    
    return true;
}

void ssd1306_clear(void) {
    memset(ssd1306_buffer, 0, sizeof(ssd1306_buffer));
}

void ssd1306_show(void) {
    ssd1306_send_command(SSD1306_COLUMN_ADDR);
    ssd1306_send_command(0);
    ssd1306_send_command(SSD1306_WIDTH - 1);
    ssd1306_send_command(SSD1306_PAGE_ADDR);
    ssd1306_send_command(0);
    ssd1306_send_command((SSD1306_HEIGHT / 8) - 1);
    
    ssd1306_send_data(ssd1306_buffer, sizeof(ssd1306_buffer));
}

void ssd1306_draw_pixel(int x, int y, uint8_t color) {
    if (x < 0 || x >= SSD1306_WIDTH || y < 0 || y >= SSD1306_HEIGHT) {
        return;
    }
    
    if (color) {
        ssd1306_buffer[x + (y / 8) * SSD1306_WIDTH] |= (1 << (y % 8));
    } else {
        ssd1306_buffer[x + (y / 8) * SSD1306_WIDTH] &= ~(1 << (y % 8));
    }
}

void ssd1306_draw_line(int x0, int y0, int x1, int y1, uint8_t color) {
    int dx = abs(x1 - x0);
    int dy = abs(y1 - y0);
    int sx = (x0 < x1) ? 1 : -1;
    int sy = (y0 < y1) ? 1 : -1;
    int err = dx - dy;
    
    while (1) {
        ssd1306_draw_pixel(x0, y0, color);
        
        if (x0 == x1 && y0 == y1) break;
        
        int e2 = 2 * err;
        if (e2 > -dy) {
            err -= dy;
            x0 += sx;
        }
        if (e2 < dx) {
            err += dx;
            y0 += sy;
        }
    }
}

void ssd1306_draw_rect(int x, int y, int width, int height, uint8_t color, bool filled) {
    if (filled) {
        for (int i = 0; i < height; i++) {
            ssd1306_draw_line(x, y + i, x + width - 1, y + i, color);
        }
    } else {
        ssd1306_draw_line(x, y, x + width - 1, y, color);
        ssd1306_draw_line(x + width - 1, y, x + width - 1, y + height - 1, color);
        ssd1306_draw_line(x + width - 1, y + height - 1, x, y + height - 1, color);
        ssd1306_draw_line(x, y + height - 1, x, y, color);
    }
}

void ssd1306_draw_char(int x, int y, char c, uint8_t size) {
    if (c < 32 || c > 126) {
        c = '?';
    }
    
    const uint8_t *char_data = font5x8[c - 32];
    
    for (uint8_t i = 0; i < 5; i++) {
        uint8_t line = char_data[i];
        for (uint8_t j = 0; j < 8; j++) {
            if (line & 0x01) {
                if (size == 1) {
                    ssd1306_draw_pixel(x + i, y + j, 1);
                } else {
                    ssd1306_draw_rect(x + i * size, y + j * size, size, size, 1, true);
                }
            }
            line >>= 1;
        }
    }
}

void ssd1306_draw_string(int x, int y, const char *str, uint8_t size) {
    int cursor_x = x;
    
    while (*str) {
        if (*str == '\n') {
            cursor_x = x;
            y += 8 * size;
        } else {
            ssd1306_draw_char(cursor_x, y, *str, size);
            cursor_x += 6 * size;
            
            if (cursor_x >= SSD1306_WIDTH - 6 * size) {
                cursor_x = x;
                y += 8 * size;
            }
        }
        str++;
    }
}

void ssd1306_set_contrast(uint8_t contrast) {
    ssd1306_send_command(SSD1306_SET_CONTRAST);
    ssd1306_send_command(contrast);
}

void ssd1306_invert(bool invert) {
    if (invert) {
        ssd1306_send_command(SSD1306_INVERT_DISPLAY);
    } else {
        ssd1306_send_command(SSD1306_NORMAL_DISPLAY);
    }
}

void ssd1306_power(bool on) {
    if (on) {
        ssd1306_send_command(SSD1306_DISPLAY_ON);
    } else {
        ssd1306_send_command(SSD1306_DISPLAY_OFF);
    }
}
